import numpy as np


class DetectionService:

    def __init__(self, detection_file):
        self.detection_file = detection_file

    def load_detections(self):
        """
        Load detection proposals generated by the
        FocalNet detection stage.

        Expected format per line:

        cx cy width height confidence
        """

        detections = np.loadtxt(
            self.detection_file,
            dtype=np.float32
        )

        # If there is only one detection,
        # convert it into a 2D array.
        if detections.ndim == 1:
            detections = detections.reshape(1, -1)

        # Validate the proposal format.
        if detections.shape[1] != 5:
            raise ValueError(
                "Detection file must contain "
                "5 values per proposal: "
                "cx cy width height confidence"
            )

        return detections